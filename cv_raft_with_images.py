import cv2
import numpy as np
import torch
import torchvision.transforms.functional as F
from torchvision.models.optical_flow import raft_large, Raft_Large_Weights
from sklearn.ensemble import RandomForestClassifier
import matplotlib.pyplot as plt

# ==========================================
# 0. Generate Synthetic "Structural" Images
# ==========================================
def create_test_images():
    """Creates a baseline image of a structure and a warped/shifted second image."""
    # Create a blank white canvas
    img1 = np.ones((480, 640, 3), dtype=np.uint8) * 255

    # Draw a mock "bridge" structure (pillars and beams)
    cv2.rectangle(img1, (100, 200), (150, 480), (100, 100, 100), -1) # Pillar 1
    cv2.rectangle(img1, (450, 200), (500, 480), (100, 100, 100), -1) # Pillar 2
    cv2.rectangle(img1, (50, 150), (550, 200), (50, 50, 50), -1)     # Top Beam

    # Add some texture/keypoints for ORB to detect
    for i in range(100):
        x, y = np.random.randint(50, 550), np.random.randint(150, 480)
        cv2.circle(img1, (x, y), 2, (0, 0, 0), -1)

    # Create img2 by applying a slight warp (simulating structural stress/bending)
    pts1 = np.float32([[50, 150], [550, 150], [50, 480]])
    # Shift the top right point slightly down and right to simulate a sag
    pts2 = np.float32([[50, 150], [560, 160], [50, 480]])
    matrix = cv2.getAffineTransform(pts1, pts2)
    img2 = cv2.warpAffine(img1, matrix, (640, 480), borderMode=cv2.BORDER_REPLICATE)

    return img1, img2

# ==========================================
# 1. Feature Extraction (ORB)
# ==========================================
def get_orb_matches(img1, img2):
    """Finds and draws ORB matches between the two images."""
    orb = cv2.ORB_create(nfeatures=500)
    kp1, des1 = orb.detectAndCompute(img1, None)
    kp2, des2 = orb.detectAndCompute(img2, None)

    bf = cv2.BFMatcher(cv2.NORM_HAMMING, crossCheck=True)
    matches = bf.match(des1, des2)
    matches = sorted(matches, key=lambda x: x.distance)

    # Draw the top 50 matches
    match_img = cv2.drawMatches(img1, kp1, img2, kp2, matches[:50], None, flags=cv2.DrawMatchesFlags_NOT_DRAW_SINGLE_POINTS)
    return match_img

# ==========================================
# 2. Optical Flow (RAFT)
# ==========================================
def get_raft_flow(img1, img2):
    """Calculates dense optical flow and creates a visual heatmap map."""
    device = "cuda" if torch.cuda.is_available() else "cpu"
    model = raft_large(weights=Raft_Large_Weights.DEFAULT, progress=False).to(device).eval()

    # Preprocess
    t1 = F.to_tensor(cv2.cvtColor(img1, cv2.COLOR_BGR2RGB)).unsqueeze(0).to(device) * 2.0 - 1.0
    t2 = F.to_tensor(cv2.cvtColor(img2, cv2.COLOR_BGR2RGB)).unsqueeze(0).to(device) * 2.0 - 1.0

    # Inference
    with torch.no_grad():
        flow = model(t1, t2)[-1][0].cpu().numpy() # Shape: (2, H, W)

    u, v = flow[0], flow[1]
    magnitude = np.sqrt(u**2 + v**2)
    avg_displacement = np.mean(magnitude)

    # Convert flow to an RGB heatmap for visualization
    hsv = np.zeros_like(img1)
    hsv[..., 1] = 255
    mag, ang = cv2.cartToPolar(u, v)
    hsv[..., 0] = ang * 180 / np.pi / 2
    hsv[..., 2] = cv2.normalize(mag, None, 0, 255, cv2.NORM_MINMAX)
    flow_rgb = cv2.cvtColor(hsv, cv2.COLOR_HSV2RGB)

    return avg_displacement, flow_rgb

# ==========================================
# 3 & 4. Physics & ML Prediction
# ==========================================
def calculate_physics_and_risk(displacement):
    strain = displacement / 100.0 # Mock calculation
    stress_mpa = (strain * 200e9) / 1e6

    # Mock ML Model
    X_train = np.array([[0.001, 20], [0.015, 300], [0.050, 1000]])
    y_train = np.array([0, 1, 2]) # 0: Low, 1: Mod, 2: High
    clf = RandomForestClassifier(n_estimators=10, random_state=42).fit(X_train, y_train)

    pred = clf.predict([[strain, stress_mpa]])[0]
    risk_labels = {0: "Low Risk", 1: "Moderate Risk", 2: "High Risk"}

    return strain, stress_mpa, risk_labels[pred]

